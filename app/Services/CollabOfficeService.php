use Illuminate\Support\Facades\Storage;

/**
 * OnlyOffice DocumentServer 集成服务：
 * JWT 签名、编辑器配置、模板生成、文档 URL。
 */
class CollabOfficeService
{
    public function serverUrl(): string
    {
        return rtrim((string) config('collab.server_url'), '/');
    }

    public function jwtSecret(): string
    {
        return (string) config('collab.jwt_secret');
    }

    public function pmInternalUrl(): string
    {
        return rtrim((string) config('collab.pm_internal_url'), '/');
    }

    /* ---------------- JWT（HS256） ---------------- */

    private function base64UrlEncode(string $data): string
    {
        return rtrim(strtr(base64_encode($data), '+/', '-_'), '=');
    }

    /**
     * 生成 OnlyOffice 要求的 JWT（HS256）
     */
    public function generateJwt(array $payload): string
    {
        $header = $this->base64UrlEncode(json_encode(['alg' => 'HS256', 'typ' => 'JWT']));
        $body = $this->base64UrlEncode(json_encode($payload));
        $signature = hash_hmac('sha256', $header . '.' . $body, $this->jwtSecret(), true);
        return $header . '.' . $body . '.' . $this->base64UrlEncode($signature);
    }

    /* ---------------- 编辑器配置 ---------------- */

    public function documentType(string $extension): string
    {
        return match (strtolower($extension)) {
            'docx' => 'word',
            'xlsx' => 'cell',
            'pptx' => 'slide',
            default => 'word',
        };
    }

    /**
     * 构建 DocsAPI.DocEditor 的 config（含顶层 token）
     */
    public function buildEditorConfig(CollabDocument $doc, User $user, bool $canEdit): array
    {
        $config = [
            'type' => 'desktop',
            'documentType' => $this->documentType($doc->extension),
            'document' => [
                'fileType' => strtolower($doc->extension),
                'key' => $doc->doc_key,
                'title' => $doc->name . '.' . $doc->extension,
                'url' => $this->downloadUrl($doc),
                'permissions' => [
                    'edit' => $canEdit,
                    'download' => true,
                    'print' => true,
                    'review' => true,
                ],
            ],
            'editorConfig' => [
                'mode' => $canEdit ? 'edit' : 'view',
                'callbackUrl' => $this->callbackUrl($doc),
                'lang' => 'zh-CN',
                'user' => [
                    'id' => (string) $user->id,
                    'name' => $user->name,
                ],
                'customization' => [
                    'autosave' => true,
                    'forcesave' => true,
                    'compactHeader' => false,
                    'hideRightMenu' => false,
                ],
            ],
        ];

        if ($this->jwtSecret() !== '') {
            $config['token'] = $this->generateJwt([
                'document' => $config['document'],
                'editorConfig' => $config['editorConfig'],
                'documentType' => $config['documentType'],
            ]);
        }

        return $config;
    }

    /* ---------------- URL ---------------- */

    /**
     * OnlyOffice 服务器（容器内）下载文档的地址。
     * 路由本身无登录态，通过 doc_key 参数做访问控制。
     */
    public function downloadUrl(CollabDocument $doc): string
    {
        return $this->pmInternalUrl() . '/collab/download/' . $doc->id . '?k=' . urlencode($doc->doc_key);
    }

    /**
     * OnlyOffice 保存回调地址（服务器到服务器，容器内访问宿主机 PM）
     */
    public function callbackUrl(CollabDocument $doc): string
    {
        return $this->pmInternalUrl() . '/collab/callback/' . $doc->id . '?k=' . urlencode($doc->doc_key);
    }

    /* ---------------- 内置模板 ---------------- */

    /**
     * 确保三个内置模板文件存在，不存在则生成
     */
    public function ensureTemplates(): void
    {
        foreach (['docx', 'xlsx', 'pptx'] as $ext) {
            $path = config('collab.template_dir') . '/template.' . $ext;
            if (!Storage::disk('local')->exists($path)) {
                Storage::disk('local')->put($path, $this->buildTemplate($ext));
            }
        }
    }

    /**
     * 运行时生成最小有效 Office 模板（zip 结构）
     */
    public function buildTemplate(string $extension): string
    {
        return match (strtolower($extension)) {
            'docx' => $this->buildDocx(),
            'xlsx' => $this->buildXlsx(),
            'pptx' => $this->buildPptx(),
            default => throw new \InvalidArgumentException("不支持的模板类型: {$extension}"),
        };
    }

    private function zip(array $files): string
    {
        $zip = new \ZipArchive();
        $tmp = tempnam(sys_get_temp_dir(), 'collab_tpl_');
        if ($zip->open($tmp, \ZipArchive::CREATE | \ZipArchive::OVERWRITE) !== true) {
            throw new \RuntimeException('无法创建模板 zip');
        }
        foreach ($files as $name => $content) {
            $zip->addFromString($name, $content);
        }
        $zip->close();
        $data = file_get_contents($tmp);
        @unlink($tmp);
        return $data;
    }

